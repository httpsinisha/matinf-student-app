import assert from 'node:assert/strict';
import { before, after, test } from 'node:test';
import { startWordPress } from '../scripts/runtime.mjs';
import { chromium } from 'playwright';
let site;
before(async () => { site = await startWordPress({ port: 9414, storage: '.contact-test-runtime', seed: false }); }, { timeout: 240000 });
after(async () => { if (site) await site[Symbol.asyncDispose](); });
test('contact verifies students, restricts recipients, handles partial failures and suppresses retries', async () => {
  const result = await site.playground.run({ code: `<?php require '/wordpress/wp-load.php';
    $saved = get_option('matinf_contact_settings', []); $checks = []; $messages = []; $failTo = '';
    $check = function($ok, $label) use (&$checks) { if (!$ok) throw new RuntimeException($label); $checks[] = $label; };
    $mail = function($short, $args) use (&$messages, &$failTo) { $messages[]=$args; return $args['to'] !== $failTo; };
    add_filter('pre_wp_mail', $mail, 10, 2);
    $staff = wp_insert_post(['post_type'=>'mf_staff','post_title'=>'Contact fixture','post_status'=>'publish']);
    $student = 'student-' . strtolower(wp_generate_password(10,false)) . '@matinf.test';
    $settings = ['enabled'=>true,'sender'=>'sender@matinf.test','smtpHost'=>'','testMode'=>true,'testTeacher'=>'teacher@matinf.test','testStudent'=>$student];
    $call = function($path, $body) { $request = new WP_REST_Request('POST','/matinf/v1/contact/'.$path); $request->set_body_params($body); return rest_do_request($request); };
    $input = ['staffId'=>$staff,'name'=>'Student','email'=>$student,'subject'=>'Consultation','message'=>'Test message'];
    try {
      update_option('matinf_contact_settings',array_merge($settings,['enabled'=>false]),false);
      $check($call('request',$input)->get_status()===503 && !$messages,'disabled endpoint sends nothing');
      update_option('matinf_contact_settings',$settings,false);
      $check($call('request',array_merge($input,['email'=>'stranger@matinf.test']))->get_status()===400 && !$messages,'test student allowlist');
      $check($call('request',array_merge($input,['message'=>str_repeat('x',5001)]))->get_status()===400,'message length bound');
      $check($call('request',array_merge($input,['email'=>['bad']]))->get_status()===400,'invalid type rejected');
      wp_update_post(['ID'=>$staff,'post_status'=>'draft']);
      $check($call('request',$input)->get_status()===400,'unpublished professor rejected');
      wp_update_post(['ID'=>$staff,'post_status'=>'publish']);
      $start = $call('request',$input); $id=$start->get_data()['requestId'];
      preg_match('/Kod: ([0-9]{6})/', $messages[0]['message'], $match); $code=$match[1];
      $check($start->get_status()===200 && count($messages)===1 && $messages[0]['to']===$student,'code only goes to student');
      $check(!str_contains(wp_json_encode($start->get_data()),$code),'code never returned by API');
      $check($call('request',$input)->get_status()===429 && count($messages)===1,'request cooldown');
      $wrong = $code==='111111' ? '222222' : '111111';
      $check($call('confirm',['requestId'=>$id,'code'=>$wrong])->get_status()===400 && count($messages)===1,'wrong code sends nothing');
      $failTo = $student;
      $partial = $call('confirm',['requestId'=>$id,'code'=>$code]);
      $check($partial->get_status()===502 && count($messages)===3,'copy failure is reported');
      $check($messages[1]['to']==='teacher@matinf.test' && in_array('Reply-To: '.$student,$messages[1]['headers'],true),'teacher recipient and reply-to');
      $check(in_array('From: MATINF <sender@matinf.test>',$messages[1]['headers'],true),'sender is service mailbox');
      $failTo = '';
      $finish = $call('confirm',['requestId'=>$id,'code'=>$code]);
      $check($finish->get_status()===200 && count($messages)===4 && $messages[3]['to']===$student,'retry only sends missing copy');
      $check(in_array('Reply-To: teacher@matinf.test',$messages[3]['headers'],true),'student can reply to professor');
      $repeat = $call('confirm',['requestId'=>$id,'code'=>$code]);
      $check($repeat->get_status()===200 && count($messages)===4,'completed retry sends nothing');
      $state=get_transient('matinf_contact_'.$id);
      $check(!isset($state['message']) && !isset($state['name']),'successful message content discarded');
      $state['expires']=time()-1; set_transient('matinf_contact_'.$id,$state,60);
      $check($call('confirm',['requestId'=>$id,'code'=>$code])->get_status()===400,'expired request rejected');
      $state['expires']=time()+600; $state['attempts']=5; set_transient('matinf_contact_'.$id,$state,600);
      $check($call('confirm',['requestId'=>$id,'code'=>$code])->get_status()===429,'code attempts bounded');
      $state['attempts']=0; set_transient('matinf_contact_'.$id,$state,600);
      update_option('matinf_contact_settings',array_merge($settings,['testTeacher'=>'changed@matinf.test']),false);
      $check($call('confirm',['requestId'=>$id,'code'=>$code])->get_status()===400,'recipient changes invalidate request');
      update_option('matinf_contact_settings',array_merge($settings,['testStudent'=>'']),false);
      $newStudent='other-' . strtolower(wp_generate_password(10,false)) . '@matinf.test';
      $before=count($messages);
      $open=$call('request',array_merge($input,['email'=>$newStudent]));
      $openId=$open->get_data()['requestId'];
      preg_match('/Kod: ([0-9]{6})/', $messages[$before]['message'], $openMatch); $openCode=$openMatch[1];
      $check($open->get_status()===200 && count($messages)===$before+1 && $messages[$before]['to']===$newStudent,'blank student restriction accepts a new address but only sends code');
      update_option('matinf_contact_settings',$settings,false);
      $check($call('confirm',['requestId'=>$openId,'code'=>$openCode])->get_status()===400 && count($messages)===$before+1,'reinstated student restriction blocks pending confirmation');
      update_option('matinf_contact_settings',array_merge($settings,['testStudent'=>'']),false);
      $badOpenCode=$openCode==='111111' ? '222222' : '111111';
      $check($call('confirm',['requestId'=>$openId,'code'=>$badOpenCode])->get_status()===400 && count($messages)===$before+1,'arbitrary student still needs correct code');
      $check($call('confirm',['requestId'=>$openId,'code'=>$openCode])->get_status()===200 && count($messages)===$before+3 && $messages[$before+1]['to']==='teacher@matinf.test' && $messages[$before+2]['to']===$newStudent && in_array('Reply-To: '.$newStudent,$messages[$before+1]['headers'],true),'verified arbitrary student sends to shared teacher and receives own copy');
      delete_transient('matinf_contact_'.$openId);
      update_option('matinf_contact_settings',array_merge($settings,['testMode'=>false]),false);
      update_post_meta($staff,'_matinf_email','fake@example.org');
      $check(matinf_contact_recipient($staff,matinf_contact_settings())==='','placeholder recipient rejected');
      update_post_meta($staff,'_matinf_email','real@matinf.test');
      $check(matinf_contact_recipient($staff,matinf_contact_settings())==='real@matinf.test','production recipient from profile');
      $check(!get_option('matinf_contact_lock'),'lock released');
      delete_transient('matinf_contact_'.$id);
      echo wp_json_encode($checks);
    } finally {
      update_option('matinf_contact_settings',$saved,false); wp_delete_post($staff,true); remove_filter('pre_wp_mail',$mail,10);
    }
  ` });
  assert.equal(result.exitCode, 0, result.errors + result.text);
  const checks = JSON.parse(result.text);
  assert.equal(checks.length, 26, checks.join('\n'));
});

test('website contact form submits the message, confirms a code and preserves input after errors', async () => {
  const setup = await site.playground.run({ code: `<?php require '/wordpress/wp-load.php';
    $saved=get_option('matinf_contact_settings',[]);
    $id=wp_insert_post(['post_type'=>'mf_staff','post_status'=>'publish','post_title'=>'Contact browser fixture']);
    update_option('matinf_contact_settings',['enabled'=>true,'sender'=>'sender@matinf.test','testMode'=>true,'testTeacher'=>'teacher@matinf.test','testStudent'=>'student@matinf.test'],false);
    echo wp_json_encode(['id'=>$id,'saved'=>$saved,'url'=>get_permalink($id)]);
  ` });
  assert.equal(setup.exitCode, 0, setup.errors);
  const fixture = JSON.parse(setup.text);
  let browser;
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    let attempts = 0;
    await page.route('**/wp-json/matinf/v1/contact/request', async route => {
      const input = route.request().postDataJSON();
      assert.equal(input.staffId, fixture.id); assert.equal(input.message, 'Browser test message');
      await route.fulfill({ json: { requestId: 'a'.repeat(40), message: 'Kod je poslat.' } });
    });
    await page.route('**/wp-json/matinf/v1/contact/confirm', async route => {
      assert.equal(route.request().postDataJSON().requestId, 'a'.repeat(40));
      attempts++;
      await route.fulfill({ status: attempts===1 ? 400 : 200, json: attempts===1 ? { message:'Kod nije ispravan.' } : { sent:true, message:'Poruka i kopija predati su mejl serveru.' } });
    });
    await page.goto(fixture.url, { waitUntil: 'networkidle' });
    await page.getByText('Pošalji mejl profesoru', { exact: true }).click();
    await page.getByLabel('Vaše ime', { exact:true }).fill('Test student');
    await page.getByLabel('Vaš mejl', { exact:true }).fill('student@matinf.test');
    await page.getByLabel('Naslov', { exact:true }).fill('Browser test');
    await page.getByLabel('Poruka', { exact:true }).fill('Browser test message');
    await page.getByRole('button', { name:'Nastavi — pošalji kod' }).click();
    await page.getByLabel('Kod iz mejla').waitFor({ state:'visible' });
    assert.equal(await page.getByLabel('Poruka', { exact:true }).isDisabled(), true);
    await page.getByLabel('Kod iz mejla').fill('123456');
    await page.getByRole('button', { name:'Potvrdi i pošalji' }).click();
    await page.getByText('Kod nije ispravan.', { exact:true }).waitFor();
    assert.equal(await page.getByLabel('Poruka', { exact:true }).inputValue(), 'Browser test message');
    await page.getByLabel('Kod iz mejla').fill('654321');
    await page.getByRole('button', { name:'Potvrdi i pošalji' }).click();
    await page.getByText('Poruka i kopija predati su mejl serveru.', { exact:true }).waitFor();
    assert.equal(await page.getByRole('button', { name:'Potvrdi i pošalji' }).isVisible(), false);
    assert.equal(await page.getByLabel('Poruka', { exact:true }).inputValue(), '');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  } finally {
    await browser?.close();
    await site.playground.run({ code: `<?php require '/wordpress/wp-load.php';
      update_option('matinf_contact_settings',json_decode(base64_decode('${Buffer.from(JSON.stringify(fixture.saved)).toString('base64')}'),true),false);
      wp_delete_post(${fixture.id},true);
    ` });
  }
});
